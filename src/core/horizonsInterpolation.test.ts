const PARENT: Record<string, string> = {
  phobos: 'mars',
  amalthea: 'jupiter',
  mimas: 'saturn',
  pluto: 'sun',
  jupiter: 'sun',
  uranus: 'sun',
  styx: 'pluto',
  hyperion: 'saturn',
  nereid: 'neptune',
};
const BOUND_KM: Record<string, number> = {
  phobos: 45,
  amalthea: 2_500,
  mimas: 1_800,
  pluto: 30,
  jupiter: 300,
  uranus: 60,
  styx: 400,
  hyperion: 400,
  nereid: 100,
};
const KM_PER_AU = 149_597_870.7;
const horizons = horizonsServiceFromDisk();

describe('interpolation des binaires entre deux échantillons', () => {
  it.each(VECTORS)('%s @ %s', (name, iso, x, y, z) => {
    const date = new Date(iso);
    const p =
      PARENT[name] === 'sun'
        ? horizons.getHeliocentricAU(name, date)
        : horizons.getParentRelativeAU(name, PARENT[name], date);
    expect(p, `${name}: hors couverture`).not.toBeNull();
    // Scène -> écliptique J2000 : (X, −Z, Y).
    const errorKm = Math.hypot(
      p!.x * KM_PER_AU - x,
      -p!.z * KM_PER_AU - y,
      p!.y * KM_PER_AU - z
    );
    expect(errorKm, `${name} @ ${iso}`).toBeLessThan(BOUND_KM[name]);
  });
});
